export function getStoryBySlug(slugOrId) {
  if (!slugOrId) return null;
  const target = slugOrId.toLowerCase();
  return (
    LETS_READ_STORIES.find(
      (s) => s.slug.toLowerCase() === target || s.id.toLowerCase() === target
    ) || null
  );
}

